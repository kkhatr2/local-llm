"""Promote only verified, digest-shaped image references into deploy/image-digests.yaml."""

from __future__ import annotations

import argparse
import re
from pathlib import Path

_DIGEST = re.compile(
    r"^[a-z0-9._/-]+@sha256:[0-9a-f]{64}$"
)


def _validate(value: str, flavor: str) -> str:
    if not _DIGEST.fullmatch(value):
        raise ValueError(f"{flavor} must be a repository@sha256:<64 hex> digest")
    return value


def main(argv: list[str] | None = None) -> int:
    parser = argparse.ArgumentParser()
    parser.add_argument("--cpu", required=True)
    parser.add_argument("--cuda", required=True)
    parser.add_argument(
        "--path",
        default=str(Path(__file__).with_name("image-digests.yaml")),
    )
    args = parser.parse_args(argv)

    cpu = _validate(args.cpu, "cpu")
    cuda = _validate(args.cuda, "cuda")
    path = Path(args.path)
    path.write_text(
        "# Phase 2 image promotion pins (not secret material).\n"
        "# Generated by deploy/promote_digests.py after all supply-chain gates pass.\n"
        f"cpu: {cpu}\n"
        f"cuda: {cuda}\n",
        encoding="utf-8",
    )
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
